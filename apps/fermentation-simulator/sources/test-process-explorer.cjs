const assert = require('node:assert/strict');
const fs = require('node:fs');
const model = require('../simulation-core.js');
const example = require('./simulation-example.js');
const view = require('./process-explorer.js');
const snapshot = scenario => model.inspectTime(scenario, 12).trace;
const s = example.create();
const original = structuredClone(s), trace = snapshot(s), traceBefore = structuredClone(trace);
const values = view.summaries(trace, s);
assert.deepEqual(s, original, 'Display does not mutate settings');
assert.deepEqual(trace, traceBefore, 'Display does not mutate state');
assert.equal(view.stages.length, 8);
assert.equal(view.overview.length, 6);
assert.deepEqual(view.stages.flatMap(stage => stage[2]), ['initial','environment','controller','feed','flows','growth','biomass','acetate','product','ph','oxygen','totals','failures','final']);
const summarizedNumber = (node, label) => Number(values[node].find(row => row[0] === label)[1].split(' ')[0]);
const near = (a,b) => assert(Math.abs(a-b) < Math.max(1,Math.abs(b))*.0001, `${a} vs ${b}`);
near(summarizedNumber('broth','Volume'),trace.after.volume);
near(summarizedNumber('broth','DO'),trace.nodes.oxygen.doAfter);
near(summarizedNumber('solve','Growth μ'),trace.nodes.growth.mu);
near(summarizedNumber('cells','Viable biomass at end'),trace.after.viableBiomassMass);
near(summarizedNumber('material','Biomass formed'),trace.nodes.biomass.biomassGrowth+trace.nodes.acetate.acetateBiomass);
near(summarizedNumber('ph','Base delivery'),trace.nodes.ph.baseDelivered/(.06*trace.dt));
for (const rows of Object.values(values)) assert(!/NaN|undefined|Infinity|Unavailable/.test(JSON.stringify(rows)));
let edges = view.overviewEdges(s);
assert(!edges.some(e=>e[0]==='broth'&&e[1]==='feed'), 'Scheduled feeding is not feedback-controlled');
assert(edges.some(e=>e[0]==='do'&&e[2].includes('O₂ fixed')));
s.feed.strategy='do-stat'; s.reactor.oxygenSupplyMode='adaptive';
edges=view.overviewEdges(s);
assert(edges.some(e=>e[0]==='broth'&&e[1]==='feed'));
assert(edges.some(e=>e[0]==='do'&&e[2]==='rpm / air / O₂'));
s.process.phMode='uncontrolled';
assert(!view.overviewEdges(s).some(e=>e[0]==='ph'||e[1]==='ph'));
s.process.type='batch';
assert(!view.overviewEdges(s).some(e=>e[0]==='broth'&&e[1]==='feed'));
assert.equal(view.summaries(snapshot(s),s).feed[0][1], 'Batch · no feed');
s.biology.enableOverflow=false;
assert.equal(view.summaries(snapshot(s),s).cells[3][1], 'Disabled');
s.process.strictFailures=true;s.process.phSetpoint=3;
const dead=snapshot(s);
assert.equal(view.summaries(dead,s).cells[0][1],'0 gDCW');
const html=fs.readFileSync(__dirname+'/simulation.html','utf8');
for (const name of ['process-explorer.js','process-explorer.css']) assert(html.includes(name));
assert(html.indexOf('process-explorer.js') < html.indexOf('simulation-map.js'));
assert(html.includes('id="example-process"'));
const js=fs.readFileSync(__dirname+'/simulation-map.js','utf8');
assert(js.includes('explorer.update({trace:result.trace'), 'One trace supplies both views');
assert(!js.includes('setItem('), 'Inspector does not write simulator storage');
assert(js.includes('toFixed(8)'), 'Sub-second timeline positions retain enough precision');
console.log('PASS: two-view trace parity, eight-stage coverage, conditional feedback, batch, disabled acetate, strict death and non-mutating presentation.');
