const assert=require('assert'),fs=require('fs'),vm=require('vm'),{selectRows}=require('./databank.js');
const rows=require('./audited-sheets.json'),ctx={window:{}};vm.runInNewContext(fs.readFileSync(__dirname+'/../source-derivations.js','utf8'),ctx);
rows.forEach(r=>r.numeric=Object.fromEntries(r.parameters.map(p=>[p.key,ctx.window.FermentationSourceDerivations.valueFor(r,p.key)])));
const base={min:'',max:'',volumeBasis:'maxVolume',custom:false,search:'',manufacturer:'',parameter:'',evidence:'',order:'name'};
assert.strictEqual(selectRows(rows,base).length,68);
assert.strictEqual(selectRows(rows,{...base,custom:true}).length,71);
const small=selectRows(rows,{...base,min:'0',max:'2',parameter:'powerNumber'});
assert(small.length>0&&small.every(r=>r.maxVolume<=2));
assert(small.some(r=>r.id==='sartorius-ambr-15'));
assert(small.some(r=>r.id==='sartorius-univessel-su-2'));
const supported=selectRows(rows,{...base,min:'0',max:'2',parameter:'powerNumber',evidence:'Source-supported'});
assert(supported.some(r=>r.id==='sartorius-ambr-15'));
assert(supported.every(r=>r.parameters.find(p=>p.key==='powerNumber').status==='Source-supported'));
assert(selectRows(rows,{...base,min:'2',max:'2',volumeBasis:'overlap'}).some(r=>r.id==='sartorius-univessel-glass-5'));
assert.throws(()=>selectRows(rows,{...base,min:'3',max:'2'}));
assert.throws(()=>selectRows(rows,{...base,min:'-1'}));
assert.strictEqual(selectRows(rows,{...base,search:'nonexistent-xyz'}).length,0);
assert(selectRows(rows,{...base,manufacturer:'Sartorius'}).every(r=>r.manufacturer==='Sartorius'));
const ordered=selectRows(rows,{...base,parameter:'powerNumber',order:'value'});assert(ordered.every((r,i)=>!i||ordered[i-1].numeric.powerNumber<=r.numeric.powerNumber));
console.log(`PASS: databank filters, boundaries, evidence, sorting; ${small.length} reactors in 0-2 L example.`);
